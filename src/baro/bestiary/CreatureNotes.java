    private static void note(String id, String text) { NOTES.put(id, text); }

    /** Описание вида; для варианта без своего описания — описание родителя. */
    public static String of(Creature c, Bestiary b) {
        for (Creature x = c; x != null; x = x.parent() == null ? null : b.creature(x.parent()).orElse(null)) {
            String n = NOTES.get(x.id().toLowerCase(Locale.ROOT));
            if (n != null) return n;
            if (x.parent() != null && x.parent().equalsIgnoreCase(x.id())) break;
        }
        return null;
    }
