package baro.model;


import static baro.Tr.tr;
/** Навык персонажа (0–100) и за что он отвечает. */
public enum Skill {
    WEAPONS(tr("Оружие"), tr("Точность стрельбы: с низким навыком разброс пуль намного больше (у оружия это «разброс без навыка»). ")
            + tr("Нужен для крафта оружия и боеприпасов и для стрельбы из турелей.")),
    MECHANICAL(tr("Механика"), tr("Ремонт механики: насосы, двигатели, двери, генераторы кислорода, обшивка. Чем выше навык, тем быстрее ремонт. ")
            + tr("Нужен для крафта инструментов, брони и механических деталей.")),
    ELECTRICAL(tr("Электрика"), tr("Ремонт электроники: реактор, сонар, навигация, проводка. С низким навыком выше риск получить удар током. ")
            + tr("Нужен для крафта электронных компонентов, схем и аккумуляторов.")),
    MEDICAL(tr("Медицина"), tr("Лечение: насколько хорошо срабатывают препараты и перевязка. Если навык ниже требуемого для препарата, ")
            + tr("вместо обычного эффекта срабатывает эффект «при провале». Нужен для крафта медикаментов.")),
    HELM(tr("Управление"), tr("Пилотирование подлодки и работа с навигацией. Нужен для некоторых рецептов и талантов."));

    private final String title, description;

    Skill(String title, String description) { this.title = title; this.description = description; }

    public String title() { return title; }
    public String description() { return description; }

    /** Что значит требование навыка в рецепте. */
    public static String recipeNote(int level) {
        return tr("В рецепте нужен навык ") + level + tr(". Если навык ниже, изготовление идёт дольше — тем дольше, чем больше не хватает.");
    }

    /** Что значит требование навыка для применения препарата. */
    public static String useNote(int level) {
        return tr("Для успешного применения нужна Медицина ") + level + tr(". Ниже — сработает эффект «при провале» (часто слабее и с побочными эффектами).");
    }
}
